#!/usr/bin/env python3
"""Follow-up analysis for RUSA-NIDS Section 5.6.1's open question: does the
risk term's benefit track attack type?

Two things this script computes, both from data already generated by the
forest-based leave-one-day-out run (no new download, no new classifier
training):

1. Attack-type composition per day (from the Label column already present
   in datasets/scored_15k_forest/<day>-scored.csv) -- to see whether
   Tuesday's being a brute-force day is a plausible explanation for it
   being the one fold where eta=5.0 was selected.

2. For every day, dropped_deadline at eta=0.0 AND at eta=5.0 (each at the
   day's own selected slack, and also at slack=1.5 for a fair apples-to-
   apples comparison) -- not just each day's argmin. This tells us whether
   eta=5.0 is actively WORSE on the 4 days that preferred eta=0.0 (the risk
   term actively hurts there) or merely TIED/indifferent (the risk term is
   just inert there, not harmful).
"""
from __future__ import annotations

import csv
import glob
import os
from collections import Counter
from pathlib import Path

import sys
import zlib
sys.path.insert(0, os.getcwd())

from rusa_nids.real_trace import TraceWorkloadGenerator
from rusa_nids.schedulers import RusaNidsPolicy
from rusa_nids.schedulers.rusa import RusaWeights
from rusa_nids.simulate import run_simulation

DATA_DIR = "../datasets/scored_15k_forest_v2"
N_WORKERS = 2


def normalize(name: str) -> str:
    return name.strip().lower().replace(" ", "").replace("_", "")


def discover_day_files(data_dir: str):
    folds = {}
    for path in sorted(glob.glob(os.path.join(data_dir, "*.csv"))):
        key = Path(path).stem.split("-")[0].split("_")[0]
        folds.setdefault(key, []).append(path)
    return folds


def label_composition(csv_paths):
    counts = Counter()
    for path in csv_paths:
        with open(path, newline="", encoding="utf-8", errors="replace") as f:
            reader = csv.DictReader(f)
            norm_map = {normalize(k): k for k in reader.fieldnames}
            label_key = norm_map.get("label")
            for row in reader:
                label = (row.get(label_key) or "").strip()
                counts[label] += 1
    return counts


def main():
    folds = discover_day_files(DATA_DIR)
    print("=== Attack-type composition per day (from scored_15k_forest) ===")
    for day in sorted(folds):
        counts = label_composition(folds[day])
        total = sum(counts.values())
        top = counts.most_common(8)
        print(f"\n{day} (n={total}):")
        for label, c in top:
            print(f"  {label}: {c} ({100.0*c/total:.1f}%)")

    print("\n=== eta=0.0 vs eta=5.0 dropped_deadline, same slack=1.5, per day ===")
    for day in sorted(folds):
        seed = zlib.crc32(day.encode()) % (2**31)
        gen = TraceWorkloadGenerator(
            csv_paths=folds[day],
            risk_col="detector_prob",
            uncertainty_col="detector_uncertainty",
            max_rows=15000,
            seed=seed,
        )
        row = {"day": day, "n": len(gen)}
        for eta in (0.0, 5.0):
            weights = RusaWeights(eta=eta, urgency_slack_s=1.5)
            policy = RusaNidsPolicy(weights=weights)
            gen.reset()
            res = run_simulation(policy=policy, n_workers=N_WORKERS, n_flows=len(gen), generator=gen, seed=seed)
            row[f"dropped_eta{eta}"] = res.dropped_deadline
        print(row)


if __name__ == "__main__":
    main()
